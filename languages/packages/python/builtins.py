# neos python builtins: provided by the runtime plugin neos.runtime.python (a function whose body is "..." is imported as "python::f(types)")

def print(value: str) -> None: ...
def print(value: int) -> None: ...
def print(value: float) -> None: ...
def print(value: bool) -> None: ...
def input() -> str: ...
# (an int (of any size); a call with an int argument is compiled as a conversion (a small integer: the VM's neos::string_from_i64))
def str(value: int) -> str: ...
def str(value: float) -> str: ...
def str(value: bool) -> str: ...
def int(value: str) -> int: ...
def float(value: str) -> float: ...
# (a compiler intrinsic: a string's length in code points is recorded in its header)
def __neos_string_code_points(value: str) -> int: ...
def len(value: str) -> int:
    return __neos_string_code_points(value)
def abs(value: int) -> int: ...
def abs(value: float) -> float: ...
# (an object: the Python object protocol)
def print(value: object) -> None: ...
def str(value: object) -> str: ...
def repr(value: object) -> str: ...
def len(value: object) -> int: ...
def int(value: object) -> int: ...
def float(value: object) -> float: ...
def abs(value: object) -> object: ...
def bool(value: object) -> bool: ...
# (an f-string's replacement field: its value converted (0, 'r', 's' or 'a') and formatted)
def __fstring(value: object, conversion: int, spec: str) -> str: ...
def __fstring(value: object) -> str: ...
# (a generator's yield (see the compiler's closures.cpp): the value sent)
def __yield(value: object) -> object: ...
# (any and all of a generator expression (see the compiler's rewrite_comprehensions): of a list of their result)
def __any_items(value: object) -> object: ...
def __all_items(value: object) -> object: ...
def __is_int(value: object) -> bool: ...
def __as_int(value: object) -> int: ...
