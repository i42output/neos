// The C compiler plugin's language compiler: each source fragment is a translation unit, which it preprocesses (its own pass over 
// the source, before it is parsed) and builds a syntax tree of from the C constructs that the schema's concepts emit (see 
// neos/language/c.hpp); when the program's last translation unit has been parsed (the prelude's (the C library's own C code) and 
// the program's) it analyses them and generates a WebAssembly function for each function, and the entry point (the runtime 
// initialized, the static data, then main called).

#pragma once

#include <deque>
#include <map>
#include <memory>
#include <optional>
#include <set>
#include <string>
#include <vector>
#include <neolib/neolib.hpp>
#include <neolib/core/pair.hpp>
#include <neos/language/language_compiler.hpp>
#include <neos/language/c.hpp>
#include <neos/bytecode/opcodes.hpp>
#include "model.hpp"

namespace neos::compilers::c
{
    using namespace neos::language;
    using bytecode::opcode;

    class program;

    // a compile error: the node (its position) and the message
    struct compile_error : std::runtime_error
    {
        compile_error(node const* aNode, std::string const& aMessage) : std::runtime_error{ aMessage }, where{ aNode } {}
        node const* where;
    };

    // (a function's control flow that the structured method cannot generate: the function generated by the dispatch method)
    struct dispatch_needed : compile_error
    {
        using compile_error::compile_error;
    };

    class compiler : public language_compiler
    {
    public:
        compiler();
        ~compiler();
        // i_language_compiler
    public:
        bool one_program() const override { return true; }    ///< (a C program's translation units: one program, linked by C's rules)
        void begin_compilation() override;
        void begin_pass() override;
        void begin_fragment(i_source_fragment& aFragment) override;
        void end_fragment() override;
        bool parsable_source(neolib::i_string_view const& aSource, neolib::i_string& aResult, neolib::i_vector<std::uint32_t>& aPositions) const override;
        void emit_construct(std::uint32_t aConstruct, neolib::i_string_view const& aSource) override;
        bool frame_name(std::uint32_t aFunction, neolib::i_string& aName) override;
        std::uint32_t source_line(i_source_fragment const& aFragment, std::size_t aPosition) override;
        void diagnose(i_source_fragment const& aFragment, std::uint32_t& aLine, std::uint32_t& aColumn, std::uint32_t& aEndLine, 
            std::uint32_t& aEndColumn, neolib::i_string& aType, neolib::i_string& aMessage, neolib::i_string& aReport) override;
    public:
        i_code_generator& gen() { return generator(); }
        std::map<std::uint32_t, std::string>& frame_names() { return iFrameNames; }
        void emit_entry(fragment const& aStatement) { push_operand(operand_type{ aStatement }); generator().end_indented(); }   ///< (the entry point's code)
        void warning(translation_unit const* aUnit, source_location const& aWhere, std::string const& aMessage);
        void warning(node const* aWhere, std::string const& aMessage);
        std::optional<std::string> const& packages_folder() const { return iPackagesFolder; }
    private:
        // the syntax tree
        node* make_node(construct aKind, std::string_view aSource);
        void build(construct aKind, std::string_view aSource);
        void unit_parsed(node* aUnit);
        void dump(node* aNode, int aDepth = 0) const;
        void generate();
        void report(compile_error const& aError);
        void report(translation_unit const& aUnit, source_location const& aWhere, std::string const& aMessage);
        preprocessor::options preprocessor_options() const;
    private:
        struct fragment_state
        {
            std::string_view base;          ///< (the fragment's source, as the parser has it)
            translation_unit* unit = nullptr;
            i_source_fragment* pending = nullptr;   ///< (a fragment whose preprocessing waits for the prelude (its headers' folder))
        };
        void preprocess(i_source_fragment& aFragment, fragment_state& aState);
        void import_libraries(std::vector<std::string> const& aIdentifiers);
        std::vector<fragment_state> iFragments;
        std::deque<node> iNodes;
        std::vector<node*> iStack;
        std::deque<translation_unit> iUnits;
        std::vector<translation_unit*> iParsed;     ///< (the units, in the order parsed)
        std::optional<std::string> iPackagesFolder; ///< (the language's packages (the prelude's folder): its include folder has the standard headers)
        std::size_t iProgramUnits = 0u;     ///< (the program's translation units (not the prelude's), as the declaration pass found them)
        std::size_t iUnitsParsed = 0u;      ///< (this pass's)
        // (the library's files in C (lib/ in the packages folder): compiled with a program only if it uses a function that one provides)
        std::map<std::string, std::string> iLibraryProvides;   ///< (a function's name: its file)
        bool iLibraryRead = false;
        std::set<std::string> iImportedLibraries;   ///< (this pass's)
        std::set<std::string> iPendingLibraries;    ///< (imported, not yet parsed)
        bool iGenerated = false;                    ///< (this pass's)
        std::map<std::uint32_t, std::string> iFrameNames;
        std::unique_ptr<program> iProgram;
        // (the preprocessor's outputs, by source: a pass preprocesses the same sources again)
        std::map<std::pair<std::string, std::string>, std::pair<preprocessor::output, std::vector<std::string>>> iPreprocessed;
        std::map<std::string, std::pair<std::string, std::string>> iSources;   ///< (a file's source as written and its preprocessed text: a 
                                                                                ///< fragment compiled again (by the next pass) has the latter)
        struct pending_error
        {
            std::string file;
            std::uint32_t line = 0u;
            std::uint32_t column = 0u;
            std::string message;
        };
        std::optional<pending_error> iPendingError;
    };
}
